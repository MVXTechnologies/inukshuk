#!/usr/bin/env node
// @ts-check
/**
 * Writes artifact.json for a patched Hermes build (hermes-android.yml):
 * every Maven file of com.facebook.hermes:hermes-android:<version> with its
 * size and SHA-256, and the GNU build-ids of every libhermesvm.so inside the
 * AARs (all variants, stripped jni/ and unstripped prefab/ copies), grouped
 * by ABI. The output is committed as plugins/patched-hermes/artifact.json.
 *
 *   artifact-manifest.js <maven-version-dir> <extracted-libs-dir> <repo> <run-url>
 */
const { createHash } = require('node:crypto');
const { readFileSync, readdirSync, statSync } = require('node:fs');
const { join } = require('node:path');

const build = require('./build.json');
const { describeLib } = require('./hermesCheck');
const { findLibs } = require('./verify-hermes');

/** Maven files Gradle reads; checksum side files and maven-metadata are not needed. */
const MAVEN_FILE = /\.(aar|jar|module|pom)$/;

/**
 * @param {Array<{ name: string, sha256: string, size: number }>} files
 * @param {Array<{ abi: string | undefined, buildId: string | undefined }>} libs
 * @param {{ repo: string, runUrl: string }} where
 */
function artifactManifest(files, libs, where) {
  /** @type {Record<string, string[]>} */
  const buildIds = {};
  for (const { abi, buildId } of libs) {
    if (!abi || !buildId) throw new Error('a library has no ABI or build-id');
    const ids = (buildIds[abi] ??= []);
    if (!ids.includes(buildId)) ids.push(buildId);
  }
  for (const ids of Object.values(buildIds)) ids.sort();
  return {
    $comment: [
      'OUTPUT of .github/workflows/hermes-android.yml for build.json (#648): the published Maven files',
      'of the patched com.facebook.hermes:hermes-android, pinned by size + SHA-256, and the GNU build-ids',
      'of every libhermesvm.so they contain. plugins/withPatchedHermes.js downloads exactly these files;',
      'verify-hermes.js `packaged` fails any Android build whose libhermesvm.so is not one of these builds.',
      'Generated by plugins/patched-hermes/artifact-manifest.js; copy it from the run, never edit by hand.',
    ],
    version: build.version,
    releaseTag: build.releaseTag,
    baseUrl: `https://github.com/${where.repo}/releases/download/${build.releaseTag}`,
    mavenPath: `com/facebook/hermes/hermes-android/${build.version}`,
    builtBy: where.runUrl,
    files: [...files].sort((a, b) => a.name.localeCompare(b.name)),
    buildIds: Object.fromEntries(Object.entries(buildIds).sort(([a], [b]) => a.localeCompare(b))),
  };
}

/** @param {string[]} argv */
function main(argv) {
  const [mavenDir, libsDir, repo, runUrl] = argv;
  if (!mavenDir || !libsDir || !repo || !runUrl) {
    console.error(
      'usage: artifact-manifest.js <maven-version-dir> <libs-dir> <owner/repo> <run-url>',
    );
    return 2;
  }
  const files = readdirSync(mavenDir)
    .filter((n) => MAVEN_FILE.test(n))
    .map((name) => {
      const buf = readFileSync(join(mavenDir, name));
      return {
        name,
        sha256: createHash('sha256').update(buf).digest('hex'),
        size: statSync(join(mavenDir, name)).size,
      };
    });
  const libs = findLibs(libsDir).map((p) => describeLib(readFileSync(p)));
  console.log(JSON.stringify(artifactManifest(files, libs, { repo, runUrl }), null, 2));
  return 0;
}

if (require.main === module) process.exitCode = main(process.argv.slice(2));

module.exports = { MAVEN_FILE, artifactManifest };
