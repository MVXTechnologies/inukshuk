/**
 * The demo library: real Québec City corridors, hand-anchored.
 *
 * Every route below is a real place — the Plaines, the Promenade
 * Samuel-De Champlain, the Corridor des Cheminots, les Sentiers du Moulin,
 * le Mont-Sainte-Anne — traced through a dozen-odd anchor coordinates with
 * hand-read elevations. `synth.ts` inflates each one into a several-thousand
 * point recording.
 *
 * They are spread deliberately across folders, categories, seasons and shapes
 * (an evening walk, a half marathon, a 90-minute classic ski, two untimed
 * planned routes, one uncategorized import) because the Library screen's job
 * is to make a heterogeneous list readable, and twenty identical 10 km runs
 * would not test that at all.
 *
 * Anchor spacing is the thing to get right. Anchors 300 m apart over a 4 km
 * area with 600 m of climb produce a 15% average grade, which is not a trail —
 * it is a cliff, and every derived number (pace, moving time, grade colouring)
 * comes out visibly wrong. Mountain routes therefore span kilometres, the way
 * the real switchbacked trails do.
 */

export interface DemoFolder {
  id: string;
  name: string;
  createdAt: number;
}

export interface DemoRoute extends SynthOptions {
  id: string;
  /** Built-in category id from `@core/library/categories`, a custom id, or
   *  undefined for a deliberately uncategorized import. */
  category?: string;
  /** Owning folder id, or undefined for Ungrouped. */
  folderId?: string;
}

