def served_sources(conf):
    """[(source id, region label)] in regions.json order, each id once."""
    out, seen = [], set()
    for region in conf['regions']:
        for sid in region['sources']:
            if sid not in seen:
                seen.add(sid)
                out.append((sid, region['label']))
    return out


def entries(conf, attribution):
    by_id = {e['source']: e for e in attribution}
    out = []
    for sid, label in served_sources(conf):
        e = by_id.get(sid)
        if e is None:
            raise SystemExit(f'{sid} is not in attribution.json')
        producer = e['producer'].strip().rstrip('.')
        out.append({
            'id': sid,
            'region': label,
            'name': e['name'].strip(),
            'producer': producer,
            'license': e['license'].strip(),
            'licensePdf': e.get('license_pdf', ''),
            'website': e.get('website', ''),
            'credit': REQUIRED_TEXT.get(sid, f'{producer} ({e["license"].strip()})'),
            'short': SHORT.get(sid, producer),
        })
    return out


def _ts(s):
    """A single-quoted TypeScript string literal (Prettier's style)."""
    if any(c in s for c in '\n\r`'):
        raise ValueError(f'unexpected character in credit text: {s!r}')
    if "'" in s and '"' not in s:
        return '"' + s.replace('\\', '\\\\') + '"'
    return "'" + s.replace('\\', '\\\\').replace("'", "\\'") + "'"


def render_ts(conf, attribution):
    items = entries(conf, attribution)
    shorts = []
    for e in items:
        if e['short'] not in shorts:
            shorts.append(e['short'])
    labels = ', '.join(r['label'] for r in conf['regions'])
    lines = [
        '/**',
        ' * Credits for the precise elevation tiles (#725), served by the tiles Worker at',
        ' * /dem/{z}/{x}/{y}.png. GENERATED by `infra/tiles/nas/dem/dem.py credits --write`',
        ' * from Mapterhorn\'s attribution.json and regions.json — edit those, not this file.',
        ' * The NAS run (`dem.sh`) refuses to publish when a served source is missing here.',
        ' */',
        '',
        'export interface DemSourceCredit {',
        '  /** Mapterhorn source id. */',
        '  id: string;',
        '  /** Region it is served in. */',
        '  region: string;',
        '  name: string;',
        '  producer: string;',
        '  license: string;',
        '  licensePdf: string;',
        '  website: string;',
        '  /** The line to show (the licence\'s own wording where it prescribes one). */',
        '  credit: string;',
        '}',
        '',
        f'export const DEM_MAPTERHORN_CREDIT = {_ts(MAPTERHORN)};',
        f'export const DEM_MAPTERHORN_URL = {_ts(MAPTERHORN_URL)};',
        '',
        '/** Short attribution for the map\'s DEM source. */',
        f'export const DEM_ATTRIBUTION = {_ts("Elevation " + MAPTERHORN + " · " + " · ".join(shorts) + " · " + FALLBACK)};',
        '',
        'export const DEM_SOURCES: readonly DemSourceCredit[] = [',
    ]
    for e in items:
        lines.append('  {')
        for k in ('id', 'region', 'name', 'producer', 'license', 'licensePdf', 'website', 'credit'):
            lines.append(f'    {k}: {_ts(e[k])},')
        lines.append('  },')
    lines += [
        '];',
        '',
        '/** One line for the Credits roll (Settings › About › Map data). */',
        'export const DEM_CREDITS_LINE = `Precise elevation (' + labels
        + '): ${DEM_MAPTERHORN_CREDIT} (${DEM_MAPTERHORN_URL}) from ${[...new Set(DEM_SOURCES.map((s) => s.credit))].join(\'; \')}; elsewhere: '
        + FALLBACK + '`;',
        '',
    ]
    return '\n'.join(lines)


def check_ts(conf, text):
    """Served source ids the TypeScript module does not credit."""
    return [sid for sid, _ in served_sources(conf) if f"id: '{sid}'" not in text]
