"""Credits for the precise elevation tiles, as a TypeScript module the app imports.

Generated from Mapterhorn's attribution.json (one entry per source: name,
producer, licence, website, licence PDF) for the sources regions.json lets us
serve. A licence that prescribes its own wording gets it from REQUIRED_TEXT.
"""

MAPTERHORN = '© Mapterhorn'
MAPTERHORN_URL = 'https://mapterhorn.com/attribution'
FALLBACK = 'Mapzen / AWS Terrain Tiles'

